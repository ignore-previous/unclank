"""Write skills/<skill>/references/evidence.md from the research files.

Each skill's SKILL.md cites tell IDs in square brackets, e.g. [D08-001]. This
script collects those IDs, looks them up in research/domains/ and writes the
evidence file the skill loads when it needs the reasoning or the sources.

Usage: python scripts/build_evidence.py [skill ...]   (default: every skill)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

from research import ROOT, Entry, Source, load

SKILLS = ROOT / "skills"
CITED = re.compile(r"\[(D\d{2}-N?\d{2,3})\]")
REPO_URL_NOTE = "../../../research/"


def cited_ids(skill_md: Path) -> list[str]:
    seen: dict[str, None] = {}
    for tid in CITED.findall(skill_md.read_text(encoding="utf-8")):
        seen.setdefault(tid, None)
    return list(seen)


def render_entry(e: Entry, sources: dict[str, Source]) -> str:
    lines = [f"## {e.id} {e.title}", ""]
    if e.is_not_a_tell:
        lines.append(f"- Not a tell. {e.fields.get('Why it is fine', '')}")
    else:
        lines.append(f"- Label: {e.label}")
        lines.append(f"- Confidence: {e.fields.get('Confidence', '')}")
        for key in ("Dated", "Why it reads as AI", "Rule", "Applies to",
                    "Means for a small creator", "Fix", "Fixable", "Flag"):
            if key in e.fields:
                lines.append(f"- {key}: {e.fields[key]}")
    lines.append(f"- Full record: {REPO_URL_NOTE}domains/{e.domain}.md")
    srcs = [sources[s] for s in e.source_ids if s in sources]
    if srcs:
        lines.append("- Sources:")
        for s in srcs:
            status = f", {s.status}" if s.status else ""
            lines.append(f"  - {s.id}: {s.title} ({s.date}{status}) <{s.url}>")
    lines.append("")
    return "\n".join(lines)


def render(skill: str, entries: dict[str, Entry], sources: dict[str, Source]) -> tuple[list[str], str]:
    """Return the cited IDs and the evidence file text for one skill."""
    skill_md = SKILLS / skill / "SKILL.md"
    ids = cited_ids(skill_md)
    missing = [i for i in ids if i not in entries]
    if missing:
        raise SystemExit(f"{skill}: SKILL.md cites unknown tells: {', '.join(missing)}")
    tells = [entries[i] for i in ids if not entries[i].is_not_a_tell]
    nots = [entries[i] for i in ids if entries[i].is_not_a_tell]
    out = [
        f"# Evidence for {skill}",
        "",
        "Generated by `scripts/build_evidence.py` from `research/domains/`. Do not edit by hand;",
        "edit the research file and rebuild. Confidence: strong means 3+ independent sources,",
        "moderate means 2 (or 1 with good data), anecdotal means one opinion.",
        "Quotes are paraphrased or under 15 words. Sources marked \"search only\" were seen in",
        "search results but not opened.",
        "",
        "# Tells",
        "",
    ]
    out += [render_entry(e, sources) for e in tells]
    if nots:
        out += ["# Not a tell", ""]
        out += [render_entry(e, sources) for e in nots]
    return ids, "\n".join(out).rstrip() + "\n"


def evidence_path(skill: str) -> Path:
    return SKILLS / skill / "references" / "evidence.md"


def build(skill: str, entries: dict[str, Entry], sources: dict[str, Source]) -> list[str]:
    ids, text = render(skill, entries, sources)
    dest = evidence_path(skill)
    dest.parent.mkdir(exist_ok=True)
    dest.write_text(text, encoding="utf-8", newline="\n")
    return ids


def main(argv: list[str]) -> None:
    entries, sources = load()
    skills = argv or sorted(p.parent.name for p in SKILLS.glob("*/SKILL.md"))
    for skill in skills:
        ids = build(skill, entries, sources)
        print(f"{skill}: {len(ids)} entries")


if __name__ == "__main__":
    main(sys.argv[1:])
