"""Write evals/<case>/scaffold.sh from evals/<case>/fixture/.

`claude plugin eval` starts each run in an empty workspace. A case's scaffold
script (run with --scaffold) recreates its fixture there, so the agent sees the
project as its working directory. The fixture folder is the source; this script
turns it into heredocs (text) or base64 (binary files).

Usage: python scripts/build_scaffold.py [case ...]   (default: every case with a fixture/)
"""

from __future__ import annotations

import base64
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVALS = ROOT / "evals"


def render(case_dir: Path) -> str:
    fixture = case_dir / "fixture"
    out = [
        "#!/usr/bin/env bash",
        f"# Generated by scripts/build_scaffold.py from {case_dir.name}/fixture/. Do not edit by hand.",
        "set -euo pipefail",
        "",
    ]
    for path in sorted(p for p in fixture.rglob("*") if p.is_file()):
        rel = path.relative_to(fixture).as_posix()
        if "/" in rel:
            out.append(f"mkdir -p '{rel.rsplit('/', 1)[0]}'")
        data = path.read_bytes()
        text = ""
        try:
            text = data.decode("utf-8")
            binary = "\r" in text or "\0" in text
        except UnicodeDecodeError:
            binary = True
        if binary:
            out.append(f"base64 -d > '{rel}' <<'UNCLANK_EOF'")
            out.append(base64.b64encode(data).decode("ascii"))
        else:
            out.append(f"cat > '{rel}' <<'UNCLANK_EOF'")
            out.append(text[:-1] if text.endswith("\n") else text)
            if not text.endswith("\n"):
                raise SystemExit(f"{rel}: text fixtures must end with a newline")
        out.append("UNCLANK_EOF")
        out.append("")
    return "\n".join(out)


def cases(argv: list[str]) -> list[Path]:
    if argv:
        return [EVALS / a for a in argv]
    return sorted(p.parent for p in EVALS.glob("*/fixture") if p.is_dir())


def main(argv: list[str]) -> None:
    for case_dir in cases(argv):
        dest = case_dir / "scaffold.sh"
        dest.write_text(render(case_dir), encoding="utf-8", newline="\n")
        print(f"{case_dir.name}: scaffold.sh")


if __name__ == "__main__":
    main(sys.argv[1:])
